#!/usr/bin/env python3
"""Generate native tutorial resources from reviewed shared translations.

Run from the repository root. Screenshot PNGs are captured separately from the
native Android UI by TutorialScreenshotCaptureTest; this never modifies pixels.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/tutorial-localization'
LANGUAGES = ['en','ar','cs','de','el','es','fr','he','hi','hu','it','ja','ko','nl','pl','pt','ro','ru','sv','ur','zh-Hans']

def android_key(name):
    special = {
        'tutorial_language':'language', 'tutorial_import_action':'android.import.action',
        'tutorial_dismiss_suggestion':'dismissInvitation', 'tutorial_sample':'android.sample',
        'tutorial_view_screenshot':'viewScreenshot', 'tutorial_screenshot_description':'screenshotDescription',
        'tutorial_close_screenshot':'closeScreenshot', 'tutorial_full_screenshot':'fullScreenshot',
    }
    return special.get(name, name.removeprefix('tutorial_').replace('_','.'))

def generate(check=False):
    translations = {lang:json.loads((SOURCE/(lang+'.json')).read_text()) for lang in LANGUAGES}
    en = translations['en']
    placeholder = re.compile(r'%\d+\$(?:lld|s)|\{[A-Za-z]+\}')
    for lang, values in translations.items():
        assert values.keys() == en.keys(), f'{lang}: translation key mismatch'
        for key, value in values.items():
            assert value.strip(), f'{lang}/{key}: empty'
            assert Counter(placeholder.findall(value)) == Counter(placeholder.findall(en[key])), f'{lang}/{key}: placeholders'
    main_catalog = json.loads((ROOT/'ios/Sources/SIT/Resources/Localizable.xcstrings').read_text())['strings']
    android_root = ROOT/'android/app/src/main/res'
    native = {}
    for lang in LANGUAGES:
        folder = 'values' if lang == 'en' else 'values-'+{'zh-Hans':'zh'}.get(lang,lang)
        native[lang] = {n.attrib['name']:''.join(n.itertext()) for n in ET.parse(android_root/folder/'strings.xml').getroot() if n.tag == 'string'}
    def render(value, lang, platform):
        if platform == 'ios':
            keys = {'createTickle':'warm.contact.createTickle','groupsTab':'tab.groups','addToGroup':'contactDetail.button.addToGroup','tickleTab':'tab.tickle'}
            labels = {token:main_catalog[key]['localizations'][lang]['stringUnit']['value'] for token,key in keys.items()}
        else:
            keys = {'createTickle':'warm_contact_createTickle','groupsTab':'nav_groups','addToGroup':'contact_detail_add_to_group','tickleTab':'nav_tickle','importPhone':'import_from_phone_title'}
            labels = {token:native[lang][key] for token,key in keys.items()}
        return re.sub(r'\{([A-Za-z]+)\}',lambda match:labels[match.group(1)],value)
    outputs = {}
    catalog_path = ROOT/'ios/Sources/SIT/Resources/Tutorials.xcstrings'
    catalog = json.loads(catalog_path.read_text())
    for key, entry in catalog['strings'].items():
        semantic = key.removeprefix('tutorial.')
        entry['localizations'] = {lang:{'stringUnit':{'state':'translated','value':render(values[semantic],lang,'ios')}} for lang,values in translations.items()}
    outputs[catalog_path] = json.dumps(catalog,ensure_ascii=False,indent=2)+'\n'
    swift_path = ROOT/'ios/Sources/SIT/Views/Tutorials/TutorialView.swift'
    swift = swift_path.read_text()
    def default(match):
        key = match.group(1).removeprefix('tutorial.')
        return match.group(0).replace(match.group(2),render(en[key],"en","ios"))
    swift = re.sub(r'String\(localized: "(tutorial\.[^"]+)", defaultValue: "([^"]*)", table: "Tutorials"\)',default,swift)
    outputs[swift_path] = swift
    android_root = ROOT/'android/app/src/main/res'
    names = [node.attrib['name'] for node in ET.parse(android_root/'values/tutorials.xml').getroot()]
    for lang,values in translations.items():
        resource_lang = {'zh-Hans':'zh'}.get(lang,lang)
        dirs = ['values'] if lang=='en' else ['values-'+resource_lang]
        if lang=='he': dirs.append('values-iw')
        lines = ['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/sync-tutorial-localizations.py. -->','<resources>']
        native_xml = ET.parse(android_root/dirs[0]/'strings.xml').getroot()
        native_strings = {n.attrib['name']:''.join(n.itertext()) for n in native_xml if n.tag=='string'}
        for name in names:
            value = native_strings['warm_contact_createTickle'] if name=='tutorial_tickle_action' else render(values[android_key(name)],lang,'android')
            value = value.replace('$lld','$d')
            value = escape(value).replace("'", "\\'").replace('"','\\"')
            lines.append(f'    <string name="{name}">{value}</string>')
        lines.append('</resources>')
        for folder in dirs: outputs[android_root/folder/'tutorials.xml']='\n'.join(lines)+'\n'
    stale=[]
    for path, content in outputs.items():
        if not path.exists() or path.read_text()!=content:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    if check and stale: raise SystemExit('Outdated generated resources:\n'+'\n'.join(stale))
    print(f'{len(LANGUAGES)} languages; {len(en)} shared keys; {len(outputs)} native resource files validated')

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true')
    generate(parser.parse_args().check)
